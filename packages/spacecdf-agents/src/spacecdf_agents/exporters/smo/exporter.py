    def _gen_hk_structures(self) -> dict:
        structures = []
        for subsys, sid, interval in [
            ("eps", 1, 1.0), ("aocs", 2, 4.0), ("tcs", 3, 60.0),
            ("obdh", 4, 8.0), ("ttc", 5, 8.0), ("payload", 6, 10.0),
        ]:
            params = []
            for pdef in self._allocator.param_defs:
                if pdef["subsystem"] == subsys:
                    params.append({
                        "param_id": pdef["id"],
                        "pack_format": "H",  # uint16 default
                        "scale": 100,
                    })
            if params:
                structures.append({
                    "sid": sid,
                    "name": subsys.upper(),
                    "interval_s": interval,
                    "parameters": params,
                })
        return {"structures": structures}

