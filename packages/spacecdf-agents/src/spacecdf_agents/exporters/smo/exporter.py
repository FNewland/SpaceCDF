    def _validate(self, result: SMOExportResult) -> None:
        """Run cross-reference validation checks."""
        params_yaml = result.files.get("telemetry/parameters.yaml", {})
        param_ids = {p["id"] for p in params_yaml.get("parameters", [])}

        # Check HK structures reference valid param_ids
        hk = result.files.get("telemetry/hk_structures.yaml", {})
        for struct in hk.get("structures", []):
            for p in struct.get("parameters", []):
                if p["param_id"] not in param_ids:
                    result.validation_errors.append(
                        f"HK SID {struct['sid']}: param_id 0x{p['param_id']:04X} not in parameters.yaml"
                    )

        # Check S12 references valid param_ids
        s12 = result.files.get("monitoring/s12_definitions.yaml", {})
        for rule in s12.get("s12_definitions", []):
            if rule["param_id"] not in param_ids:
                result.validation_warnings.append(
                    f"S12 rule '{rule['name']}': param_id 0x{rule['param_id']:04X} not in parameters.yaml"
                )

        # Check param ID range overlaps
        ranges: dict[str, list[int]] = {}
        for pdef in params_yaml.get("parameters", []):
            subsys = pdef.get("subsystem", "unknown")
            ranges.setdefault(subsys, []).append(pdef["id"])
        for subsys, ids in ranges.items():
            if ids:
                id_min, id_max = min(ids), max(ids)
                for other_subsys, other_ids in ranges.items():
                    if other_subsys != subsys and other_ids:
                        other_min, other_max = min(other_ids), max(other_ids)
                        if id_min <= other_max and other_min <= id_max:
                            result.validation_warnings.append(
                                f"Param ID ranges overlap: {subsys} (0x{id_min:04X}-0x{id_max:04X}) "
                                f"and {other_subsys} (0x{other_min:04X}-0x{other_max:04X})"
                            )
