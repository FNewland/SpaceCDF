    def _gen_orbit(self, state: DesignState, req: MissionRequirements) -> dict:
        # Look up ground stations from KB or use defaults
        gs_data = []
        gs_defaults = {
            "KSAT Svalbard": {"lat_deg": 78.229, "lon_deg": 15.407, "alt_km": 0.458},
            "KSAT Troll": {"lat_deg": -72.012, "lon_deg": 2.535, "alt_km": 1.275},
            "DSN Goldstone": {"lat_deg": 35.426, "lon_deg": -116.890, "alt_km": 1.0},
            "DSN Madrid": {"lat_deg": 40.431, "lon_deg": -4.249, "alt_km": 0.8},
            "DSN Canberra": {"lat_deg": -35.402, "lon_deg": 148.982, "alt_km": 0.7},
        }
        for gs_name in req.ground_stations:
            if gs_name in gs_defaults:
                gs_data.append({"name": gs_name, **gs_defaults[gs_name], "min_elevation_deg": 5.0})
            else:
                gs_data.append({"name": gs_name, "lat_deg": 78.23, "lon_deg": 15.41,
                                "alt_km": 0.0, "min_elevation_deg": 5.0})

        return generate_orbit_yaml(
            altitude_km=req.orbit.altitude_km,
            inclination_deg=req.orbit.inclination_deg,
            eccentricity=req.orbit.eccentricity,
            ground_stations=gs_data,
        )

