"""SpaceCDF — SMO Simulator Configuration Exporter.

Generates the complete config directory structure that the
SpaceMissionSimulation engine loads. Produces ~20 YAML files
from a converged DesignState.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from spacecdf_common.agents.base import DesignState
from spacecdf_common.models.study import MissionRequirements

from .orbit_gen import generate_orbit_yaml
from .param_id_allocator import ParamIDAllocator


@dataclass
class SMOExportResult:
    """Result of SMO config export."""
    files: dict[str, Any] = field(default_factory=dict)  # path -> yaml dict
    validation_errors: list[str] = field(default_factory=list)
    validation_warnings: list[str] = field(default_factory=list)
    param_id_map: dict[str, int] = field(default_factory=dict)

    @property
    def is_valid(self) -> bool:
        return len(self.validation_errors) == 0


class SMOExporter:
    """Exports SpaceCDF design state to SMO simulator configuration."""

    def __init__(self):
        self._allocator = ParamIDAllocator()

    def export(
        self,
        state: DesignState,
        requirements: MissionRequirements,
    ) -> SMOExportResult:
        """Generate complete SMO config from design state."""
        result = SMOExportResult()

        # Allocate parameter IDs
        self._allocator.allocate_from_state(state)
        result.param_id_map = dict(self._allocator._allocations)

        # Generate each config file
        result.files["mission.yaml"] = self._gen_mission(state, requirements)
        result.files["orbit.yaml"] = self._gen_orbit(state, requirements)

        # Subsystem configs
        result.files["subsystems/eps.yaml"] = self._gen_eps(state)
        result.files["subsystems/aocs.yaml"] = self._gen_aocs(state)
        result.files["subsystems/tcs.yaml"] = self._gen_tcs(state)
        result.files["subsystems/ttc.yaml"] = self._gen_ttc(state)
        result.files["subsystems/obdh.yaml"] = self._gen_obdh(state)
        result.files["subsystems/payload.yaml"] = self._gen_payload(state)
        result.files["subsystems/fdir.yaml"] = self._gen_fdir(state)

        # Telemetry
        result.files["telemetry/parameters.yaml"] = self._gen_parameters()
        result.files["telemetry/hk_structures.yaml"] = self._gen_hk_structures()

        # Monitoring
        result.files["monitoring/s12_definitions.yaml"] = self._gen_s12(state)
        result.files["monitoring/s19_rules.yaml"] = self._gen_s19()

        # Events and commands
        result.files["events/event_catalog.yaml"] = self._gen_events()
        result.files["commands/tc_catalog.yaml"] = self._gen_commands()

        # Planning
        result.files["planning/activity_types.yaml"] = self._gen_activities(state)

        # FDIR procedures
        for name, content in self._gen_fdir_procedures(state).items():
            result.files[f"fdir/procedures/{name}.yaml"] = content

        # MCS
        result.files["mcs/positions.yaml"] = self._gen_mcs_positions()

        # Validate cross-references
        self._validate(result)

        return result

    def export_to_disk(
        self,
        state: DesignState,
        requirements: MissionRequirements,
        output_dir: str | Path,
    ) -> SMOExportResult:
        """Export to disk as YAML files."""
        result = self.export(state, requirements)
        output_dir = Path(output_dir)

        for filepath, content in result.files.items():
            full_path = output_dir / filepath
            full_path.parent.mkdir(parents=True, exist_ok=True)
            with open(full_path, "w") as f:
                yaml.dump(content, f, default_flow_style=False, sort_keys=False)

        return result

